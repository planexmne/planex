const supportedLanguages = ["sr", "en", "ru"];
const nav = document.getElementById("site-nav");
const toggle = document.querySelector(".menu-toggle");
const languageSwitcher = document.querySelector(".lang-switcher");
const languageButton = document.getElementById("language-button");
const languageCurrent = document.querySelector("[data-lang-current]");
const languageOptions = document.querySelectorAll("[data-lang-option]");
const metaDescription = document.querySelector('meta[name="description"]');

const getByPath = (object, path) =>
  path.split(".").reduce((accumulator, key) => accumulator?.[key], object);

const normalizeLanguage = (value) => {
  if (!value) {
    return null;
  }

  const language = value.toLowerCase();

  if (language.startsWith("ru")) {
    return "ru";
  }

  if (language.startsWith("en")) {
    return "en";
  }

  if (language.startsWith("sr")) {
    return "sr";
  }

  return null;
};

const getStoredLanguage = () => {
  try {
    return normalizeLanguage(localStorage.getItem("language"));
  } catch (error) {
    return null;
  }
};

const saveLanguage = (language) => {
  try {
    localStorage.setItem("language", language);
  } catch (error) {
    // Ignore localStorage failures.
  }
};

const detectLanguage = () => {
  const storedLanguage = getStoredLanguage();
  if (storedLanguage) {
    return storedLanguage;
  }

  const browserLanguages = Array.isArray(navigator.languages) && navigator.languages.length
    ? navigator.languages
    : [navigator.language];

  for (const browserLanguage of browserLanguages) {
    const normalized = normalizeLanguage(browserLanguage);
    if (normalized) {
      return normalized;
    }
  }

  return "sr";
};

const updateMenuToggleLabel = (language) => {
  const labels = translations[language].ui;
  const isOpen = nav.classList.contains("is-open");
  // Update both aria-label (for screen readers) and aria-expanded state
  toggle.setAttribute("aria-label", isOpen ? labels.closeMenu : labels.openMenu);
  toggle.setAttribute("aria-expanded", isOpen ? "true" : "false");
};

const closeLanguageMenu = () => {
  languageSwitcher.classList.remove("is-open");
  languageButton.setAttribute("aria-expanded", "false");
};

const openLanguageMenu = () => {
  languageSwitcher.classList.add("is-open");
  languageButton.setAttribute("aria-expanded", "true");
  // If mobile nav is open, close it when opening language menu
  if (nav.classList.contains("is-open")) {
    nav.classList.remove("is-open");
    updateMenuToggleLabel(document.documentElement.lang || initialLanguage);
  }
};

const setActiveLanguageOption = (language) => {
  languageOptions.forEach((option) => {
    const isActive = option.dataset.langOption === language;
    option.classList.toggle("is-active", isActive);
    option.setAttribute("aria-checked", String(isActive));
  });
};

const applyLanguage = (language) => {
  const safeLanguage = supportedLanguages.includes(language) ? language : "sr";
  const dictionary = translations[safeLanguage];

  document.documentElement.lang = safeLanguage;
  document.title = dictionary.meta.title;
  metaDescription.setAttribute("content", dictionary.meta.description);
  languageCurrent.textContent = safeLanguage.toUpperCase();
  languageButton.setAttribute("aria-label", dictionary.language.label);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = getByPath(dictionary, element.dataset.i18n);
    if (typeof value === "string") {
      element.textContent = value;
    }
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const value = getByPath(dictionary, element.dataset.i18nHtml);
    if (typeof value === "string") {
      element.innerHTML = value;
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = getByPath(dictionary, element.dataset.i18nAlt);
    if (typeof value === "string") {
      element.setAttribute("alt", value);
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = getByPath(dictionary, element.dataset.i18nAriaLabel);
    if (typeof value === "string") {
      element.setAttribute("aria-label", value);
    }
  });

  setActiveLanguageOption(safeLanguage);
  updateMenuToggleLabel(safeLanguage);
};

const initialLanguage = detectLanguage();
applyLanguage(initialLanguage);

languageButton.addEventListener("click", () => {
  if (languageSwitcher.classList.contains("is-open")) {
    closeLanguageMenu();
    return;
  }

  openLanguageMenu();
});

languageOptions.forEach((option) => {
  option.addEventListener("click", () => {
    const language = supportedLanguages.includes(option.dataset.langOption)
      ? option.dataset.langOption
      : "sr";

    saveLanguage(language);
    applyLanguage(language);
    closeLanguageMenu();
  });
});

document.addEventListener("click", (event) => {
  // Close language menu when clicking outside of it
  if (!languageSwitcher.contains(event.target)) {
    closeLanguageMenu();
  }

  // Close mobile nav when clicking outside of it (and outside the toggle button)
  if (
    nav.classList.contains("is-open") &&
    !nav.contains(event.target) &&
    !toggle.contains(event.target)
  ) {
    nav.classList.remove("is-open");
    updateMenuToggleLabel(document.documentElement.lang || initialLanguage);
  }
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    // Close language menu and mobile nav on Escape
    closeLanguageMenu();
    if (nav.classList.contains("is-open")) {
      nav.classList.remove("is-open");
      updateMenuToggleLabel(document.documentElement.lang || initialLanguage);
    }
  }
});

toggle.addEventListener("click", () => {
  nav.classList.toggle("is-open");
  // When nav opens, ensure language menu is closed
  if (nav.classList.contains("is-open")) {
    closeLanguageMenu();
  }
  updateMenuToggleLabel(document.documentElement.lang || initialLanguage);
});